"""Application ports: domain code depends on contracts, not storage or transport."""
from typing import Any, Protocol


class TravelerRepository(Protocol):
    def create_session(self, nickname: str, avatar: str) -> dict: ...
    def authenticate(self, token: str) -> Any: ...
    def progress(self, traveler_id: str) -> dict: ...
    def submit_attempt(self, traveler_id: str, scenario_id: str, answers: list[str], key: str) -> dict: ...
    def collect_events(self, traveler_id: str, events: list[dict]) -> int: ...
    def event_summary(self, traveler_id: str) -> dict: ...
    def add_chat(self, traveler_id: str, room: str, text: str) -> dict: ...
    def recent_chat(self, room: str) -> list[dict]: ...


class RoomBroker(Protocol):
    async def join(self, room: str, channel: str) -> None: ...
    async def leave(self, room: str, channel: str) -> None: ...
    async def publish(self, room: str, payload: dict) -> None: ...
